// Vocabulário por lição de 汉语教程 第一册(上): palavra, pinyin e classe conforme o livro.
// Os significados em português foram escritos para este app, no sentido usado em cada lição.
//
// w(hanzi, pinyin, classe, significado, partes, opções)
//   partes: "字 pinyin significado|字 pinyin significado", um trecho por hanzi da palavra.
//   opções: { note, name, src, show, pShow }
//     name: nome próprio (专名)
//     src:  "glossario" (só no glossário do livro) ou "texto" (só no texto da lição)
//     show / pShow: grafia exibida quando o livro usa parênteses, como 没(有)

const w = (h, p, c, m, parts = '', opts = {}) => ({
  h,
  p,
  c,
  m,
  parts: parts
    ? parts.split('|').map((part) => {
        const [ch, py, ...rest] = part.trim().split(' ');
        return { h: ch, p: py, m: rest.join(' ') };
      })
    : [],
  ...opts,
});
const n = (h, p, m, parts = '', opts = {}) => w(h, p, 'nome', m, parts, { name: true, ...opts });

